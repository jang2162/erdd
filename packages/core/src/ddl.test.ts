/**
 * 방언 간 이동(설계 §4.5). mysql 은 접미로, 나머지 셋은 **기본 타입 + `CHECK (col >= 0)`** 로
 * 나간다 — 「이 컬럼은 음수가 될 수 없다」가 대상 DB 에서 실제로 강제되게 한다.
 *
 * ⚠️ **mysql 만 보면 CHECK 경로가 무테스트다** — 네 방언 전부의 출력을 고정한다.
 */
describe('generateDdl — 부호 없음', () => {
  const line = (d: Dialect, m = unsignedModel()) =>
    generateDdl(m, d).split('\n').find((l) => l.trim().startsWith('ORD_NO') || l.trim().startsWith('"ORD_NO"')
      || l.trim().startsWith('[ORD_NO]') || l.trim().startsWith('QTY'))?.trim()

  it('mysql 은 접미를 내고 CHECK 를 내지 않는다', () => {
    expect(generateDdl(unsignedModel(), 'mysql')).toContain('ORD_NO INT UNSIGNED AUTO_INCREMENT NOT NULL')
    expect(generateDdl(unsignedModel(), 'mysql')).not.toContain('>= 0')
  })
  it('나머지 세 방언은 기본 타입 + CHECK 를 낸다', () => {
    // 인용은 `quoteIdentifier` 규칙 그대로다 — 안전 패턴이고 예약어가 아니면 인용하지 않는다.
    expect(line('postgresql')).toContain('CHECK (ORD_NO >= 0)')
    expect(line('postgresql')).toContain('integer')
    expect(line('mssql')).toContain('CHECK (ORD_NO >= 0)')
    expect(line('mssql')).toContain('INT ')
    expect(line('oracle')).toContain('CHECK (ORD_NO >= 0)')
    expect(line('oracle')).toContain('NUMBER(10)')
  })
  it('예약어 컬럼명은 방언 규칙으로 인용된다', () => {
    const m = unsignedModel()
    m.columns['c1']!.physicalName = 'ORDER'
    expect(generateDdl(m, 'postgresql')).toContain('CHECK ("ORDER" >= 0)')
    expect(generateDdl(m, 'mssql')).toContain('CHECK ([ORDER] >= 0)')
  })
  it('부호 있는 정수에는 CHECK 가 없다', () => {
    for (const d of ['postgresql', 'mysql', 'oracle', 'mssql'] as const) {
      expect(generateDdl(unsignedModel('INT'), d)).not.toContain('>= 0')
    }
  })

  /**
   * ⚠️ 판정 기준은 **해석된 논리 타입**이다 — `ddlWarnings` 의 기존 결함(설계 §3.4 다)을
   * 답습하면 도메인을 지정한 컬럼은 CHECK 도 경고도 못 받는다.
   */
  it('도메인의 논리 타입이 부호 없음이면 그 컬럼도 CHECK 를 받는다', () => {
    expect(generateDdl(domainModel('INT UNSIGNED'), 'postgresql')).toContain('CHECK (QTY >= 0)')
    expect(generateDdl(domainModel('INT UNSIGNED'), 'mysql')).toContain('QTY INT UNSIGNED NOT NULL')
  })
  it('방언별 물리 타입 오버라이드가 있어도 CHECK 는 나간다 — 저장 형태와 값 제약은 배타적이지 않다', () => {
    const ddl = generateDdl(domainModel('INT UNSIGNED', { postgresql: 'int8' }), 'postgresql')
    expect(ddl).toContain('int8')
    expect(ddl).toContain('CHECK (QTY >= 0)')
  })
  /**
   * ⚠️ **CHECK 와 경고의 판정이 갈리는 유일한 자리다.** 오버라이드가 있으면 사용자가 고른 물리
   * 타입의 값 범위를 우리가 알 수 없으므로 **경고는 내지 않는다**(`resolveColumn` 의 기존 동작).
   * 반면 `CHECK` 는 낸다 — 저장 형태와 값 제약은 배타적이지 않다(위 케이스).
   *
   * 이 사이클이 `ddlWarnings` 를 `resolveColumnType(c.type, …)` 에서 `resolveColumn(c, …)` 으로
   * 옮기면서 **기존 `ORACLE_WARN` 의 빈도도 함께 바뀌었다**: 도메인 지정 컬럼에는 이제 뜨고
   * (설계 §3.4 다 해소), **오버라이드가 있으면 안 뜬다.** 뒤쪽 갈래를 여기서 잠근다 — 위
   * 케이스만 있으면 오버라이드에도 경고를 내도록 되돌려도 전건 초록이다(실증).
   */
  it('오버라이드가 있으면 경고는 내지 않는다 — CHECK 와 판정이 갈린다', () => {
    const withOverride = domainModel('BIGINT UNSIGNED', { oracle: 'NUMBER(20)' })
    expect(ddlWarnings(withOverride, 'oracle')).toEqual([])
    // 짝: 오버라이드가 없으면 같은 도메인이 경고를 낸다.
    expect(ddlWarnings(domainModel('BIGINT UNSIGNED'), 'oracle').join('\n')).toContain('ORD.QTY')

    // ORACLE_WARN(부호 없음과 무관한 기존 표)도 같은 규칙을 탄다.
    expect(ddlWarnings(domainModel('JSON', { oracle: 'CLOB' }), 'oracle')).toEqual([])
    expect(ddlWarnings(domainModel('JSON'), 'oracle').join('\n')).toContain('CLOB으로 변환됩니다')
  })
  it('도메인 허용값 CHECK 와 함께 두 개가 나간다', () => {
    const m = domainModel('INT UNSIGNED')
    m.domains['d']!.allowedValues = ['1', '2']
    const ddl = generateDdl(m, 'postgresql')
    expect(ddl).toContain("CHECK (QTY IN ('1', '2'))")
    expect(ddl).toContain('CHECK (QTY >= 0)')
  })

  it('ddlWarnings 가 상한 손실을 알린다 — 도메인 지정 컬럼도(설계 §3.4 다)', () => {
    expect(ddlWarnings(unsignedModel(), 'postgresql').join('\n')).toContain('ORD.ORD_NO')
    expect(ddlWarnings(unsignedModel(), 'postgresql').join('\n')).toContain('CHECK (컬럼 >= 0)')
    expect(ddlWarnings(domainModel('INT UNSIGNED'), 'postgresql').join('\n')).toContain('ORD.QTY')
    expect(ddlWarnings(unsignedModel(), 'mysql')).toEqual([])
  })
})

/**
 * 테이블 옵션(설계 §5.4). `)` 뒤, **`COMMENT` 앞**에 붙는다 — 파서의 테이블 코멘트 추출이
 * `group.tail` 에서 첫 `COMMENT` 키워드를 찾으므로 옵션이 앞이어야 그 스캔이 맞는다.
 */
describe('generateDdl — 테이블 옵션', () => {
  const OPTS = { postgresql: '', mysql: 'ENGINE=InnoDB DEFAULT CHARSET=utf8mb4', oracle: 'TABLESPACE users', mssql: '' }

  it('그 방언의 문자열을 닫는 괄호 뒤에 붙인다', () => {
    const m = usersModel()
    expect(generateDdlRaw(m, 'mysql', { kind: 'all' }, DEFAULT_NAMING_RULES, OPTS))
      .toContain(') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;')
    expect(generateDdlRaw(m, 'oracle', { kind: 'all' }, DEFAULT_NAMING_RULES, OPTS))
      .toContain(') TABLESPACE users;')
  })

  it('COMMENT 앞에 온다 — 파서의 코멘트 스캔이 그대로 맞는다', () => {
    const m = usersModel()
    m.tables['t']!.logicalName = '사용자'
    expect(generateDdlRaw(m, 'mysql', { kind: 'all' }, DEFAULT_NAMING_RULES, OPTS))
      .toContain(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT '사용자';")
  })

  /**
   * ⚠️ **짝 구조**(HANDOFF 3.17). 위 케이스만 있으면 배선을 끊어도 「빈 값일 때 같다」가
   * 안 걸리고, 아래만 있으면 빈 문자열이라 배선을 끊어도 결과가 같다. 둘이 함께 갈린다.
   */
  it('빈 문자열이면 한 글자도 달라지지 않는다', () => {
    const m = usersModel()
    const empty = { postgresql: '', mysql: '', oracle: '', mssql: '' }
    for (const d of ['postgresql', 'mysql', 'oracle', 'mssql'] as const) {
      expect(generateDdlRaw(m, d, { kind: 'all' }, DEFAULT_NAMING_RULES, empty))
        .toBe(generateDdlRaw(m, d, { kind: 'all' }, DEFAULT_NAMING_RULES))
    }
  })

  it('그 방언의 칸만 나간다 — 다른 방언의 문법이 새지 않는다', () => {
    const m = usersModel()
    const ddl = generateDdlRaw(m, 'postgresql', { kind: 'all' }, DEFAULT_NAMING_RULES, OPTS)
    expect(ddl).not.toContain('ENGINE')
    expect(ddl).not.toContain('TABLESPACE')
  })
})

// ── MySQL nullable TIMESTAMP ────────────────────────────────────────────────

/**
 * MySQL·MariaDB 서버가 `explicit_defaults_for_timestamp = 0` 이면 `NULL` 을 명시하지 않은
 * `TIMESTAMP` 컬럼을 제멋대로 `NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP`
 * 로 만든다 — nullable 로 설계한 컬럼이 실제 DB 에서 NOT NULL 이 되고 UPDATE 마다 값이 조용히 바뀐다.
 *
 * ⚠️ 판정 기준이 위 CHECK 와 **반대**다. 여기는 **실제로 나가는 물리 타입**(`r.sql`)으로 본다 —
 * `NULL` 명시는 저장 형태의 문제이고, CHECK 는 값의 제약이라 논리 타입이 맞다.
 */
describe('generateDdl — MySQL nullable TIMESTAMP', () => {
  function tsModel(over: Partial<Column> = {}): ProjectModel {
    const m = createEmptyModel()
    m.tables['t'] = tbl('t', 'ORD')
    m.columns['c1'] = col('c1', 't', 'ORD_NO', 'BIGINT', { isPk: true, nullable: false, order: 0 })
    m.columns['c2'] = col('c2', 't', 'REG_DT', 'TIMESTAMPTZ', { order: 1, ...over })
    return m
  }
  /** 도메인의 mysql 물리 타입 오버라이드로만 TIMESTAMP 가 되는 모델(논리 타입은 TIMESTAMP 가 아니다). */
  function overrideModel(): ProjectModel {
    const m = tsModel()
    m.domains['d'] = {
      id: 'd', name: '등록일시', category: null, logicalType: 'DATETIME',
      dialectTypes: { postgresql: null, mysql: 'TIMESTAMP', oracle: null, mssql: null },
      defaultValue: null, allowedValues: [], description: null, origin: null,
    }
    m.columns['c2'] = { ...m.columns['c2']!, type: '', domainId: 'd' }
    return m
  }

  it('nullable TIMESTAMP 에 NULL 을 명시한다', () => {
    expect(generateDdl(tsModel(), 'mysql')).toContain('REG_DT TIMESTAMP NULL')
  })

  // ⚠️ 논리 타입으로 판정하면 이 경로가 조용히 빠진다 — 오버라이드가 물리 타입을 갈아치운다.
  it('도메인의 mysql 물리 타입 오버라이드가 TIMESTAMP 여도 NULL 이 붙는다', () => {
    expect(generateDdl(overrideModel(), 'mysql')).toContain('REG_DT TIMESTAMP NULL')
  })

  // 타입 조건 단독 잠금 — dialect 가드가 사라져도 이 케이스는 안 걸린다.
  it('mysql 이어도 TIMESTAMP 가 아니면 NULL 을 붙이지 않는다', () => {
    const m = tsModel()
    m.columns['c2'] = { ...m.columns['c2']!, type: 'VARCHAR(100)' }
    const line = generateDdl(m, 'mysql').split('\n').find((l) => l.trim().startsWith('REG_DT'))!
    expect(line).toContain('REG_DT VARCHAR(100)')
    expect(line).not.toMatch(/\bNULL\b/)
  })

  it('NOT NULL TIMESTAMP 는 그대로이고 NULL 이 겹쳐 붙지 않는다', () => {
    const line = generateDdl(tsModel({ nullable: false }), 'mysql')
      .split('\n').find((l) => l.trim().startsWith('REG_DT'))!
    expect(line.trim()).toBe('REG_DT TIMESTAMP NOT NULL,')
  })

  /**
   * 방언 조건 단독 잠금 — 타입 가드가 살아 있어도 mysql 가드가 사라지면 걸려야 한다.
   *
   * ⚠️ **postgresql + TIMESTAMPTZ 로는 이 조건이 안 잠긴다**(실측). 그 조합의 물리 타입은
   * `timestamptz` 라 `/^TIMESTAMP\b/` 의 단어 경계에서 이미 떨어져 나가므로, mysql 가드를
   * 지워도 초록으로 남는다. 물리 타입이 **실제로 `TIMESTAMP` 로 시작하는** 비 mysql 조합을
   * 골라야 한다 — postgresql 의 DATETIME(`timestamp`) 과 oracle 의 TIMESTAMPTZ
   * (`TIMESTAMP WITH TIME ZONE`).
   */
  it('mysql 이 아닌 방언은 물리 타입이 TIMESTAMP 로 시작해도 NULL 을 붙이지 않는다', () => {
    const line = (m: ProjectModel, d: Dialect) =>
      generateDdl(m, d).split('\n').find((l) => l.trim().startsWith('REG_DT'))!
    const pg = line(tsModel({ type: 'DATETIME' }), 'postgresql')
    expect(pg).toContain('REG_DT timestamp')
    expect(pg).not.toMatch(/\bNULL\b/)
    const ora = line(tsModel(), 'oracle')
    expect(ora).toContain('REG_DT TIMESTAMP WITH TIME ZONE')
    expect(ora).not.toMatch(/\bNULL\b/)
    // 대조군: 단어 경계에서 떨어지는 postgresql 의 TIMESTAMPTZ(`timestamptz`)도 물론 안 붙는다.
    expect(line(tsModel(), 'postgresql')).toContain('REG_DT timestamptz')
  })

  // 왕복 — 명시한 NULL 이 파서에서 NOT NULL 로 뒤집히지 않는다(`notNull: false` 가 nullable 이다).
  it('낸 DDL 을 다시 파싱해도 nullable 이 유지된다', () => {
    const ddl = generateDdl(tsModel(), 'mysql')
    // ⚠️ 전제를 먼저 단언한다 — 토큰이 없는 출력도 `notNull: false` 로 읽히므로, 이것이 없으면
    // 이 테스트는 「NULL 토큰이 왕복한다」가 아니라 그냥 항상 참인 문장이 된다(실측).
    expect(ddl).toContain('REG_DT TIMESTAMP NULL')
    const parsed = parseDdl(ddl)
    const c = parsed.tables.find((t) => t.name === 'ORD')!.columns.find((x) => x.name === 'REG_DT')!
    expect(c.rawType).toBe('TIMESTAMP')
    expect(c.notNull).toBe(false)
  })
})
